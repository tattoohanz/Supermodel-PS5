#!/usr/bin/env bash
# Build Supermodel for the PS5 as the title PPSA97374, in ps5/dist/PPSA97374.
#
# The emulator core and the Vulkan renderer as they are, with Src/OSD/PS5 in
# place of the SDL front end (no SDL, no OpenGL). Linked the way PS5_Vulkan
# links titles that use RADV (tools/radv-link.sh and tools/build-radv-title.sh
# there), as XPSemu Chihiro's ps5/build-title.sh does: its CRT and C++
# allocation runtime, the AGC link stubs, the payload SDK's libc++ and platform
# layer, then ps5-native-tool for the signed eboot.bin, with PS5_Vulkan's
# libc.prx beside it.
#
# PS5_VULKAN names the PS5_Vulkan checkout (default ~/ps5/PS5_Vulkan),
# RADV_ARCHIVE the static RADV (default: its release build).
set -euo pipefail

here=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
src=$(dirname "$here")
vk=${PS5_VULKAN:-$HOME/ps5/PS5_Vulkan}
sdk_root=${PS5_PAYLOAD_SDK:-$vk/.deps/native/ps5-payload-sdk}
archive=${RADV_ARCHIVE:-$vk/.deps/native/radv-release/lib/libvulkan_radeon.ps5.a}
radv_include=$(dirname "$(dirname "$archive")")/include
native=$vk/tooling/native
tool=$vk/build/host/ps5-native-tool
param=$here/sce_sys/param.json
build=$here/build
gen=$build/gen
obj=$build/obj

for file in "$archive" "$radv_include/vulkan/vulkan_core.h" "$tool" "$param" \
        "$sdk_root/bin/prospero-lld" "$vk/tooling/prospero-clang18"; do
    [[ -e $file ]] || { echo "missing $file" >&2; exit 2; }
done
command -v ninja > /dev/null || { echo "ninja was not found" >&2; exit 2; }
host_cc=${HOST_CC:-cc}

title_id=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["titleId"])' "$param")
module_sdk=0x02000009
companion_sdk=0x08050001
fself_magic=0x1D3D154F

mkdir -p "$gen" "$obj" "$build/stubs"

# The desktop defaults (OSD/SDL/Main.cpp's DefaultConfig) for the PS5 front
# end, without the control preset at the end.
python3 - "$src/Src/OSD/SDL/Main.cpp" "$gen/DefaultConfig.inc" <<'PY'
import re, sys
text = open(sys.argv[1], encoding="utf-8").read()
start = text.index("Util::Config::Node DefaultConfig()\n{")
end = text.index("\n}\n", start) + 3
body = text[start:end]
body = body.replace("Util::Config::Node DefaultConfig()", "static Util::Config::Node UpstreamDefaultConfig()", 1)
preset = re.compile(r"\n[^\n]*ApplyControlPreset\(config, \"standard\"[^\n]*\n")
if not preset.search(body):
    sys.exit("DefaultConfig: the control preset line was not found")
body = preset.sub("\n", body)
out = "// Generated by ps5/build-title.sh from Src/OSD/SDL/Main.cpp. Do not edit.\n" + body
try:
    if open(sys.argv[2], encoding="utf-8").read() == out:
        sys.exit(0)
except FileNotFoundError:
    pass
open(sys.argv[2], "w", encoding="utf-8").write(out)
PY

# OSD/SDL/Audio.cpp as it is, on AudioOut.cpp's SDL audio: a quoted include
# looks in the source's own directory first, so it is compiled from here.
cmp -s "$src/Src/OSD/SDL/Audio.cpp" "$gen/Audio.cpp" || cp "$src/Src/OSD/SDL/Audio.cpp" "$gen/Audio.cpp"

# The 68K core's opcode tables, made by Musashi's generator on the host.
musashi=$src/Src/CPU/68K/Musashi
if [[ ! -f $gen/m68kops.c || $gen/m68kops.c -ot $musashi/m68k_in.c ]]; then
    "$host_cc" -O2 -w "$musashi/m68kmake.c" -o "$build/m68kmake"
    "$build/m68kmake" "$gen" "$musashi/m68k_in.c" > /dev/null
fi

# The compile, as a ninja file.
python3 - "$src" "$gen" "$obj" "$build/build.ninja" "$vk/tooling/prospero-clang18" "$sdk_root" \
    "$radv_include" "$here/include" <<'PY'
import os, sys
src, gen, obj, ninja_path, clang, sdk_root, radv_include, ps5_include = sys.argv[1:9]
core = """
Src/CPU/PowerPC/PPCDisasm.cpp Src/CPU/PowerPC/ppc.cpp Src/BlockFile.cpp
Src/Pkgs/unzip.c Src/Pkgs/ioapi.c Src/Pkgs/tinyxml2.cpp Src/Pkgs/volk_impl.cpp
Src/Model3/93C46.cpp Src/Model3/JTAG.cpp Src/Model3/Real3D.cpp Src/Model3/TileGen.cpp
Src/Model3/Model3.cpp Src/Model3/SoundBoard.cpp Src/Model3/DSB.cpp Src/Model3/IRQ.cpp
Src/Model3/53C810.cpp Src/Model3/PCI.cpp Src/Model3/RTC72421.cpp Src/Model3/MPC10x.cpp
Src/Model3/Crypto.cpp
Src/Model3/DriveBoard/DriveBoard.cpp Src/Model3/DriveBoard/WheelBoard.cpp
Src/Model3/DriveBoard/JoystickBoard.cpp Src/Model3/DriveBoard/SkiBoard.cpp
Src/Model3/DriveBoard/BillBoard.cpp Src/Model3/DriveBoard/Z80CTC.cpp
Src/Sound/SCSP.cpp Src/Sound/SCSPDSP.cpp Src/Sound/MPEG/MpegAudio.cpp
Src/CPU/68K/68K.cpp Src/CPU/Z80/Z80.cpp
Src/Graphics/New3D/PolyHeader.cpp Src/Graphics/New3D/R3DFloat.cpp Src/Graphics/New3D/Vec.cpp
Src/Graphics/New3D/Mat4.cpp Src/Graphics/New3D/Model.cpp
Src/Graphics/Vulkan3D/VulkanMemory.cpp Src/Graphics/Vulkan3D/VulkanRingBuffer.cpp
Src/Graphics/Vulkan3D/VulkanContext.cpp Src/Graphics/Vulkan3D/VulkanTextureCache.cpp
Src/Graphics/Vulkan3D/R3DSceneBuilder.cpp Src/Graphics/Vulkan3D/Vulkan2D.cpp
Src/Graphics/Vulkan3D/Vulkan3D.cpp
Src/Inputs/Input.cpp Src/Inputs/Inputs.cpp Src/Inputs/InputSource.cpp
Src/Inputs/InputSystem.cpp Src/Inputs/InputTypes.cpp Src/Inputs/MultiInputSource.cpp
Src/OSD/Outputs.cpp Src/OSD/Logger.cpp
Src/Util/Format.cpp Src/Util/NewConfig.cpp Src/Util/ByteSwap.cpp Src/Util/ConfigBuilders.cpp
Src/GameLoader.cpp Src/ROMSet.cpp
Src/Network/NetBoard.cpp Src/Network/SimNetBoard.cpp
Src/OSD/PS5/Main.cpp Src/OSD/PS5/PS5App.cpp Src/OSD/PS5/Display.cpp Src/OSD/PS5/Thread.cpp
Src/OSD/PS5/AudioOut.cpp Src/OSD/PS5/FileSystemPath.cpp Src/OSD/PS5/NetLoopback.cpp
Src/OSD/PS5/PS5InputSystem.cpp Src/OSD/PS5/GLStubs.cpp Src/OSD/PS5/Cost.cpp
Src/OSD/PS5/PS5Pad.cpp Src/OSD/PS5/PS5Mouse.cpp Src/OSD/PS5/Menu.cpp Src/OSD/PS5/MenuLayout.cpp Src/OSD/PS5/MenuSettings.cpp
Src/OSD/PS5/MenuControls.cpp
Src/Pkgs/imgui/imgui.cpp Src/Pkgs/imgui/imgui_draw.cpp Src/Pkgs/imgui/imgui_tables.cpp
Src/Pkgs/imgui/imgui_widgets.cpp Src/Pkgs/imgui/imgui_impl_vulkan.cpp
ps5/compat/libc_missing.c
""".split()
# The desktop Audio.cpp, compiled from a copy (see below) so its quoted
# "SDLIncludes.h" finds Src/OSD/PS5's rather than the one beside it.
core.append(os.path.join(gen, "Audio.cpp"))
musashi = ["Src/CPU/68K/Musashi/m68kcpu.c"] + [os.path.join(gen, f) for f in
    ("m68kops.c", "m68kopac.c", "m68kopdm.c", "m68kopnz.c")]

# Src/OSD/PS5 first: its Types.h, SDL.h and SDLIncludes.h stand in for the
# SDL front end's, whose directory is not on the path at all.
dirs = ["Src/OSD/PS5", "Src"]
for f in core:
    d = os.path.dirname(f)
    if d not in dirs and not d.startswith("ps5"):
        dirs.append(d)
for d in ("Src/Pkgs", "Src/Graphics", "Src/OSD", "Src/Model3"):
    if d not in dirs:
        dirs.append(d)
includes = " ".join("-I" + os.path.join(src, d) for d in dirs)
includes += f" -I{gen} -I{ps5_include} -I{radv_include}"
defines = "-DSUPERMODEL_PS5 -DGLEW_STATIC -DGLEW_NO_GLU -DIMGUI_DISABLE_DEFAULT_SHELL_FUNCTIONS"

def objname(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    return os.path.join(obj, stem + ".o")

lines = [
    f"clang = env PS5_PAYLOAD_SDK={sdk_root} sh {clang}",
    f"cxxflags = -std=c++17 -O3 -frtti -fexceptions -fcxx-exceptions -Wall -Wno-unused-variable -Wno-unused-but-set-variable -Wno-unused-function -ffunction-sections -fdata-sections {defines} {includes}",
    f"cflags = -std=gnu11 -O3 -w -ffunction-sections -fdata-sections {defines} {includes}",
    f"musashiflags = -I{os.path.join(src, 'Src/CPU/68K/Musashi')} -I{gen} '-DINLINE=static inline'",
    "rule cxx",
    "  command = $clang $cxxflags -MD -MF $out.d -c $in -o $out",
    "  depfile = $out.d",
    "  deps = gcc",
    "  description = CXX $in",
    "rule cc",
    "  command = $clang $cflags $extra -MD -MF $out.d -c $in -o $out",
    "  depfile = $out.d",
    "  deps = gcc",
    "  description = CC $in",
]
objects = []
seen = set()
for f in core + musashi:
    path = f if os.path.isabs(f) else os.path.join(src, f)
    o = objname(path)
    if o in seen:
        sys.exit(f"two sources make {o}")
    seen.add(o)
    objects.append(o)
    if path.endswith(".cpp"):
        lines.append(f"build {o}: cxx {path}")
    else:
        lines.append(f"build {o}: cc {path}")
        if f in musashi:
            lines.append("  extra = $musashiflags")
lines.append("build all: phony " + " ".join(objects))
lines.append("default all")
text = "\n".join(lines) + "\n"
open(ninja_path + ".objects", "w").write("\n".join(objects) + "\n")
try:
    if open(ninja_path).read() == text:
        sys.exit(0)
except FileNotFoundError:
    pass
open(ninja_path, "w").write(text)
PY

if ! ninja -C "$build" > "$build/ninja.log" 2>&1; then
    grep -E "error:|FAILED" -A4 "$build/ninja.log" | head -80 >&2
    echo "build-title.sh: compiling failed, the whole log is $build/ninja.log" >&2
    exit 1
fi
mapfile -t objects < "$build/build.ninja.objects"

cc() { PS5_PAYLOAD_SDK="$sdk_root" sh "$vk/tooling/prospero-clang18" "$@"; }
cc -std=c++20 -O2 -fno-exceptions -fno-rtti -c "$native/app_crt.cpp" -o "$obj/app_crt.o"
cc -std=c++20 -O2 -fno-exceptions -fno-rtti -c "$native/app_cpp_runtime.cpp" -o "$obj/app_cpp_runtime.o"

# AGC comes from system modules; these host-link stubs only name the imports.
stub() {
    local library=$1 source=$2
    cc -std=c11 -O2 -fPIC -c "$vk/$source" -o "$obj/${library}_stub.o"
    "$sdk_root/bin/prospero-lld" --shared -soname "${library}.prx" \
        -o "$build/stubs/${library}.so" "$obj/${library}_stub.o"
}
stub libSceAgc vendor/ps5/sdk/stubs/agc_canary_link_stub.c
stub libSceAgcDriver vendor/ps5/sdk/stubs/agc_driver_canary_link_stub.c

# shellcheck source=/dev/null
source "$vk/tools/radv-link.sh"
radv_link_recipe "$vk" "$sdk_root" "$archive" || exit 2
# The real IDs for the effective ones (Mesa's disk cache, Src/OSD/PS5/PS5App.cpp).
radv_link_flags+=(--wrap=geteuid --wrap=getegid)
# libc functions the console leaves unresolved for a title (XPSemu Chihiro's
# import report found these), bound to ps5/compat/libc_missing.c and kept
# local so the title doesn't export libc's names (as radv-link.sh does).
missing_libc=(mkstemp isatty umask pathconf fnmatch getnameinfo gai_strerror
    gethostbyname fork vfork setsid chroot symlink link readlink setbuf
    strdup strndup asprintf vasprintf)
{
    printf '{\n    local:\n'
    for name in "${missing_libc[@]}"; do
        radv_link_flags+=("--defsym=$name=xemu_ps5_$name")
        printf '        %s;\n' "$name"
    done
    printf '};\n'
} > "$build/libc-missing-local.map"
radv_link_flags+=(--version-script "$build/libc-missing-local.map")
"$sdk_root/bin/prospero-lld" "${radv_linker_script[@]}" --error-limit=0 \
    --eh-frame-hdr --no-dynamic-linker \
    -z nodynamic-undefined-weak "${radv_link_flags[@]}" \
    --version-script "$native/app-symbols.map" --exclude-libs=ALL \
    -e _start -o "$build/llvm-pie.elf" \
    "$obj/app_crt.o" "$obj/app_cpp_runtime.o" \
    --start-group "${objects[@]}" --end-group \
    "$build/stubs/libSceAgc.so" "$build/stubs/libSceAgcDriver.so" \
    "${radv_link_inputs[@]}" \
    --as-needed "$sdk_root"/target/lib/*.so
"$tool" link --in "$build/llvm-pie.elf" --out "$build/eboot.elf" \
    --stub-dir "$sdk_root/target/lib" --stub "$build/stubs/libSceAgc.so" \
    --stub "$build/stubs/libSceAgcDriver.so" --module-sdk "$module_sdk" \
    --companion-sdk "$companion_sdk" --file-name eboot.elf

app=$here/dist/$title_id
rm -rf -- "$app"
mkdir -p "$app/sce_sys" "$app/sce_module" "$app/Config" "$app/Assets"
"$tool" self --sign --in "$build/eboot.elf" --out "$app/eboot.bin" --magic "$fself_magic"
cp "$param" "$app/sce_sys/param.json"
# Every import's GOT slot, for the title to report the ones the console leaves
# empty (Src/OSD/PS5/PS5App.cpp): calling one jumps to 0.
llvm-readelf-18 -r --wide "$build/llvm-pie.elf" |
    awk '$3 == "R_X86_64_GLOB_DAT" || $3 == "R_X86_64_JUMP_SLOT" { print $1, $5 }' \
    > "$app/imports.txt"
# The title's art: ps5/prepare-art.sh's (ps5/assets/sce_sys, not in git), else
# the placeholder art.
for asset in icon0.png pic0.dds pic1.dds; do
    if [[ -f $here/assets/sce_sys/$asset ]]; then
        cp "$here/assets/sce_sys/$asset" "$app/sce_sys/$asset"
    elif [[ -f $here/sce_sys/$asset ]]; then
        cp "$here/sce_sys/$asset" "$app/sce_sys/$asset"
    elif [[ -f $vk/sce_sys/$asset ]]; then
        cp "$vk/sce_sys/$asset" "$app/sce_sys/$asset" # placeholder art
    fi
done
[[ -f $vk/runtime/libc.prx ]] || bash "$vk/tools/rebuild-libc.sh"
(cd "$vk/runtime" && sha256sum --check --strict --quiet libc.prx.sha256)
cp "$vk/runtime/libc.prx" "$app/sce_module/libc.prx"
# The title's own files, read from /app0.
cp "$src/Config/Games.xml" "$src/Config/Music.xml" "$app/Config/"
cp "$src/Supermodel3Bezel.png" "$app/Assets/"
# The games' own bezels, named by ROM set (ps5/assets/bezels, not in git).
if compgen -G "$here/assets/bezels/*.png" > /dev/null; then
    mkdir -p "$app/Assets/Bezels"
    cp "$here"/assets/bezels/*.png "$app/Assets/Bezels/"
fi
# The menu's font (OFL, in git) and art (ps5/prepare-menu-art.sh's, not in git).
mkdir -p "$app/Assets/Fonts"
cp "$here"/assets/fonts/* "$app/Assets/Fonts/"
for kind in boxart marquee logo backdrop header; do
    if compgen -G "$here/assets/menu/$kind/*.png" > /dev/null; then
        mkdir -p "$app/Assets/Menu/$kind"
        cp "$here"/assets/menu/$kind/*.png "$app/Assets/Menu/$kind/"
    fi
done
"$tool" self --inspect --file "$app/eboot.bin" > /dev/null
printf 'Supermodel title: %s (%s bytes)\n' "$app" "$(stat -c %s "$app/eboot.bin")"
